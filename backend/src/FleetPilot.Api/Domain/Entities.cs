namespace FleetPilot.Api.Domain;

public enum UserRole
{
    Admin = 0,
    Driver = 1,
}

public enum ShiftStatus
{
    Active = 0,
    Completed = 1,
}

public interface ISoftDeletable
{
    bool IsDeleted { get; set; }
    DateTime? DeletedAt { get; set; }
}

public interface IAuditable
{
}

public class User : ISoftDeletable, IAuditable
{
    public int Id { get; set; }
    public string Name { get; set; } = string.Empty;
    public string Email { get; set; } = string.Empty;
    public string? Phone { get; set; }
    public string PasswordHash { get; set; } = string.Empty;
    public UserRole Role { get; set; }
    public bool IsActive { get; set; } = true;
    public DateTime CreatedAt { get; set; }
    public DateTime? UpdatedAt { get; set; }
    public bool IsDeleted { get; set; }
    public DateTime? DeletedAt { get; set; }

    public Driver? Driver { get; set; }
}

public class Driver : IAuditable
{
    /// <summary>Primary key and foreign key to <see cref="User"/>.</summary>
    public int UserId { get; set; }
    public string LicenseNo { get; set; } = string.Empty;
    public DateOnly? LicenseExpiry { get; set; }

    public User User { get; set; } = null!;
    public ICollection<Shift> Shifts { get; set; } = new List<Shift>();
}

public class Vehicle : ISoftDeletable, IAuditable
{
    public int Id { get; set; }
    public string PlateNo { get; set; } = string.Empty;
    public string Make { get; set; } = string.Empty;
    public string Model { get; set; } = string.Empty;
    public int Year { get; set; }
    public string? Color { get; set; }
    public int CurrentOdometer { get; set; }
    public bool IsActive { get; set; } = true;
    public DateTime CreatedAt { get; set; }
    public DateTime? UpdatedAt { get; set; }
    public bool IsDeleted { get; set; }
    public DateTime? DeletedAt { get; set; }

    public ICollection<Shift> Shifts { get; set; } = new List<Shift>();
}

public class Shift : IAuditable
{
    public int Id { get; set; }

    /// <summary>Id generated by the app, used to make offline sync idempotent.</summary>
    public Guid ClientId { get; set; }

    public int DriverId { get; set; }
    public int VehicleId { get; set; }

    public DateTime StartTime { get; set; }
    public DateTime? EndTime { get; set; }

    public int StartKm { get; set; }
    public int? EndKm { get; set; }

    public string? StartPhotoUrl { get; set; }
    public string? EndPhotoUrl { get; set; }

    /// <summary>Value read on the device (ML Kit).</summary>
    public int? StartKmOcr { get; set; }
    public int? EndKmOcr { get; set; }

    /// <summary>Value read on the server (IOcrService), when configured.</summary>
    public int? StartKmServerOcr { get; set; }
    public int? EndKmServerOcr { get; set; }

    /// <summary>Lowest OCR confidence seen across start/end readings (0..1).</summary>
    public double? OcrConfidence { get; set; }

    public bool KmManuallyEdited { get; set; }

    public double? StartLatitude { get; set; }
    public double? StartLongitude { get; set; }
    public double? EndLatitude { get; set; }
    public double? EndLongitude { get; set; }

    /// <summary>True when a timestamp was taken from the device because the shift was recorded offline.</summary>
    public bool RecordedOffline { get; set; }

    public ShiftStatus Status { get; set; }
    public string? Notes { get; set; }

    public bool IsFlagged { get; set; }
    /// <summary>Semicolon separated list of reasons the shift was flagged.</summary>
    public string? FlagReasons { get; set; }
    public DateTime? ReviewedAt { get; set; }
    public int? ReviewedByUserId { get; set; }
    public string? ReviewNotes { get; set; }

    public DateTime CreatedAt { get; set; }
    public DateTime? UpdatedAt { get; set; }

    public Driver Driver { get; set; } = null!;
    public Vehicle Vehicle { get; set; } = null!;
}

public class RefreshToken
{
    public int Id { get; set; }
    public int UserId { get; set; }
    public string TokenHash { get; set; } = string.Empty;
    public DateTime CreatedAt { get; set; }
    public DateTime ExpiresAt { get; set; }
    public DateTime? RevokedAt { get; set; }
    public int? ReplacedByTokenId { get; set; }

    public User User { get; set; } = null!;

    public bool IsActive(DateTime now) => RevokedAt is null && ExpiresAt > now;
}

public class AuditLog
{
    public long Id { get; set; }
    public int? UserId { get; set; }
    public string? UserEmail { get; set; }
    public string Action { get; set; } = string.Empty;
    public string EntityType { get; set; } = string.Empty;
    public string EntityId { get; set; } = string.Empty;
    public string? Changes { get; set; }
    public DateTime Timestamp { get; set; }
}
